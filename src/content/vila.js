// a fala da vez de cada morador: em ordem e depois girando
export function falaDaVila(id, n, campo = 'conversa') {
  const v = VILA[id], l = v?.[campo]; if (!l?.length) return null;
  if (n <= l.length) return l[n - 1];
  const volta = campo === 'conversa' ? (v.volta ?? 0) : 0, roda = l.length - volta;
  return l[volta + ((n - 1 - l.length) % Math.max(1, roda))];
}
